#!/usr/bin/env python3
"""
gen_directed.py <out.S>

Writes a self-checking directed test for the RV32IM pipeline:
  A. forwarding (EX/MEM, MEM/WB, register-file write-through, priority, x0)
  B. load-use stalls, sub-word loads/stores
  C. control hazards (taken/not-taken, loops, JAL/JALR + link values)
  D. RV32M hazards (operand forwarding into the M unit, consumer right after,
     back-to-back M ops, load -> M, wrong-path M instruction after a flush)
  F. more interactions: branches / JALR / stores fed by DIV, MUL and loads, wrong-path DIV
     behind a stalled MUL, a DIV as the first instruction after a jump
  E. table-driven RV32M check: every pair of 8 edge values x all 8 operations,
     expected values computed by the Python golden model (rvsim.py)

Result protocol (data memory word 0 = 0x10000000):
    1 = PASS      2 = FAIL (word 1 holds the failing test id)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import rvsim

EDGE = [0x00000000, 0x00000001, 0xFFFFFFFF, 0x80000000,
        0x7FFFFFFF, 0x12345678, 0xDEADBEEF, 0x0000FFFE]

HEADER = r"""
# AUTO-GENERATED by tools/gen_directed.py - do not edit by hand
    .macro CHECK reg, val, id
    li   x29, \val
    beq  \reg, x29, ok_\@
    li   x28, \id
    j    fail
ok_\@:
    .endm

    .macro CHECKR reg, reg2, id
    beq  \reg, \reg2, ok_\@
    li   x28, \id
    j    fail
ok_\@:
    .endm

    .section .text.start
    .globl _start
_start:
    lui  x31, 0x10000             # x31 = data memory base 0x10000000
"""

BODY = r"""
# ---------------------------------------------------------------- A: forwarding
    addi x1, x0, 5
    addi x2, x1, 3                # EX/MEM forward
    add  x3, x2, x1               # EX/MEM (x2) + MEM/WB (x1)
    CHECK x2, 8, 1
    CHECK x3, 13, 2
    addi x4, x0, 7
    nop
    add  x5, x4, x4               # MEM/WB forward, both operands
    nop
    nop
    add  x6, x4, x5               # x5 is in WB: register-file write-through
    CHECK x5, 14, 3
    CHECK x6, 21, 4
    addi x7, x0, 3
    addi x7, x7, 4
    addi x7, x7, 5
    add  x7, x7, x7               # chain of EX/MEM forwards, both operands
    CHECK x7, 24, 5
    addi x8, x0, 1
    addi x8, x0, 2
    addi x8, x0, 3
    add  x9, x8, x0               # youngest producer must win
    CHECK x9, 3, 6
    addi x0, x0, 99               # writes to x0 are discarded, never forwarded
    add  x10, x0, x0
    CHECK x10, 0, 7

# ------------------------------------------------- B: load-use and memory access
    addi x1, x0, 100
    sw   x1, 8(x31)
    lw   x2, 8(x31)
    addi x3, x2, 1                # load-use: 1 stall cycle
    CHECK x3, 101, 10
    lw   x4, 8(x31)
    nop
    addi x5, x4, 2                # one instruction gap
    CHECK x5, 102, 11
    lw   x6, 8(x31)
    sw   x6, 12(x31)              # store data comes straight from a load
    lw   x7, 12(x31)
    CHECK x7, 100, 12
    addi x8, x31, 8               # pointer to word 2
    sw   x8, 16(x31)
    lw   x9, 16(x31)
    lw   x10, 0(x9)               # load -> load (address register from load)
    CHECK x10, 100, 13
    li   x1, 0x80FF7F01
    sw   x1, 20(x31)
    lb   x2, 20(x31)
    lb   x3, 21(x31)
    lb   x4, 22(x31)
    lb   x5, 23(x31)
    lbu  x6, 23(x31)
    lh   x7, 22(x31)
    lhu  x8, 22(x31)
    lh   x9, 20(x31)
    CHECK x2, 1, 14
    CHECK x3, 127, 15
    CHECK x4, -1, 16
    CHECK x5, -128, 17
    CHECK x6, 128, 18
    CHECK x7, -32513, 19
    CHECK x8, 33023, 20
    CHECK x9, 32513, 21
    li   x1, 0x11223344
    sw   x1, 24(x31)
    li   x2, 0xAA
    sb   x2, 25(x31)
    li   x3, 0xBBCC
    sh   x3, 26(x31)
    lw   x4, 24(x31)
    CHECK x4, 0xBBCCAA44, 22

# ------------------------------------------------------------ C: control hazards
    addi x20, x0, 0               # wrong-path counter: must stay 0
    addi x1, x0, 5
    addi x2, x0, 5
    beq  x1, x2, c_t1             # taken (operands forwarded)
    addi x20, x20, 1
    addi x20, x20, 1
c_t1:
    CHECK x20, 0, 30
    addi x21, x0, 0
    bne  x1, x2, c_t2             # not taken
    addi x21, x21, 7
c_t2:
    CHECK x21, 7, 31
    addi x3, x0, -1
    blt  x3, x0, c_t3             # signed: -1 < 0, taken, x3 just produced
    addi x20, x20, 1
c_t3:
    bltu x3, x0, c_t4             # unsigned: 0xFFFFFFFF < 0 is false
    addi x22, x0, 9
c_t4:
    CHECK x22, 9, 32
    CHECK x20, 0, 33
    addi x4, x0, 0
    addi x5, x0, 10
c_loop:
    add  x4, x4, x5
    addi x5, x5, -1
    bne  x5, x0, c_loop           # backward loop, sum 10..1
    CHECK x4, 55, 34
    auipc x8, 0
    jal  x6, c_t5                 # x6 = address of next instruction
    addi x20, x20, 1
c_t5:
    addi x9, x8, 8
    CHECKR x6, x9, 35
    CHECK x20, 0, 36
    auipc x10, 0
    addi x10, x10, 16             # target = the auipc below
    jalr x12, 0(x10)              # x12 = address of the skipped addi
    addi x20, x20, 1
    auipc x13, 0
    addi x14, x12, 4
    CHECKR x14, x13, 37
    CHECK x20, 0, 38
    addi x15, x0, 0
    addi x16, x0, 3
    bge  x16, x0, c_t6            # branch whose operand was just computed
    addi x15, x15, 1
c_t6:
    CHECK x15, 0, 39

# ----------------------------------------------------------- D: RV32M hazards
    addi x1, x0, 6
    addi x2, x0, 7
    mul  x3, x1, x2               # operands forwarded into the M unit
    addi x4, x3, 1                # consumer directly behind the M instruction
    CHECK x3, 42, 40
    CHECK x4, 43, 41
    addi x5, x0, 100
    div  x6, x5, x2               # x5 comes from EX/MEM
    rem  x7, x5, x2               # back-to-back M instructions
    CHECK x6, 14, 42
    CHECK x7, 2, 43
    mul  x8, x6, x6               # M result feeds the next M instruction
    div  x9, x8, x6
    CHECK x8, 196, 44
    CHECK x9, 14, 45
    sw   x5, 28(x31)
    lw   x10, 28(x31)
    mul  x11, x10, x10            # load-use into an M instruction
    CHECK x11, 10000, 46
    addi x12, x0, 50
    divu x13, x5, x2
    add  x14, x13, x12            # waits in ID during the long divide
    sub  x15, x14, x13
    CHECK x14, 64, 47
    CHECK x15, 50, 48
    addi x16, x0, 3
    beq  x0, x0, d_t1
    mul  x16, x16, x16            # wrong-path M instructions must be squashed
    div  x16, x16, x0
d_t1:
    CHECK x16, 3, 49
    mul  x17, x16, x16
    beq  x17, x17, d_t2           # branch waits for an M result
    addi x18, x0, 1
d_t2:
    CHECK x17, 9, 50
    CHECK x18, 0, 51
    addi x19, x0, 0
    div  x19, x2, x19             # divide by zero -> all ones
    rem  x23, x2, x0              # remainder by zero -> dividend
    CHECK x19, -1, 52
    CHECK x23, 7, 53

# ------------------------------- F: more M / load / control interactions (v12)
    addi x1, x0, 100
    addi x2, x0, 7
    div  x3, x1, x2               # 14
    beq  x3, x0, f_bad1           # NOT taken, operand is the DIV result (waits in ID)
    addi x4, x0, 1
    bne  x3, x0, f_t1             # taken, operand is the DIV result
    addi x4, x0, 99               # wrong path
f_t1:
    CHECK x4, 1, 60
    rem  x5, x1, x2               # 2
    blt  x5, x2, f_t2             # taken, M result compared right away
    addi x4, x0, 98
f_t2:
    CHECK x4, 1, 61
    divu x6, x1, x2               # 14
    sw   x6, 40(x31)              # store data comes from a just-finished DIV
    lw   x7, 40(x31)
    CHECK x7, 14, 62
    lw   x8, 40(x31)
    beq  x8, x6, f_t3             # load-use into a branch
    addi x4, x0, 97
f_t3:
    CHECK x4, 1, 63
    la   x9, f_t4
    sw   x9, 44(x31)
    lw   x10, 44(x31)
    jalr x11, 0(x10)              # load-use into JALR
    addi x4, x0, 96               # wrong path
f_t4:
    CHECK x4, 1, 64
    la   x12, f_t5
    addi x13, x0, 1
    mul  x14, x12, x13            # target address computed by MUL
    jalr x0, 0(x14)               # JALR to an M result
    addi x4, x0, 95
f_t5:
    CHECK x4, 1, 65
    addi x15, x0, 0
    mul  x16, x2, x2              # 49; the taken branch below does not depend on it
    beq  x0, x0, f_t6
    div  x15, x16, x2             # wrong path DIV after a stalled MUL: squashed
f_t6:
    CHECK x15, 0, 66
    CHECK x16, 49, 67
    jal  x17, f_t7
    addi x4, x0, 94
f_t7:
    div  x18, x1, x2              # DIV is the jump target (first instruction after a flush)
    add  x19, x18, x18            # 28
    CHECK x19, 28, 68
    divu x20, x1, x0              # 0xFFFFFFFF
    bltu x20, x1, f_bad1          # not taken: divide-by-zero result is the largest unsigned
    CHECK x20, -1, 69
    mul  x21, x2, x2
    div  x22, x21, x2             # back-to-back, second needs the first (7)
    mul  x23, x22, x22            # and a third (49)
    CHECK x23, 49, 70
    j    f_end
f_bad1:
    li   x28, 71
    j    fail
f_end:

# ------------------------------------- E: table driven RV32M check (all edge pairs)
    addi x1, x31, 256             # table pointer
    li   x2, @N@                  # number of entries
    li   x3, 0                    # entry index
e_loop:
    lw   x4, 0(x1)                # a
    lw   x5, 4(x1)                # b
@OPS@
    addi x1, x1, 40
    addi x3, x3, 1
    blt  x3, x2, e_loop
    j    pass

e_fail:
    addi x28, x3, 1000
    j    fail

pass:
    li   x29, 1
    sw   x29, 0(x31)
    ebreak
fail:
    sw   x28, 4(x31)
    li   x29, 2
    sw   x29, 0(x31)
    ebreak
"""


def main():
    out = sys.argv[1]
    entries = []
    for a in EDGE:
        for b in EDGE:
            entries.append([a, b] + [f(a, b) for f in rvsim.M_OPS])

    ops = []
    for i, name in enumerate(rvsim.M_NAMES):
        ops.append(f"    {name:<6} x6, x4, x5")
        ops.append(f"    lw     x7, {8 + 4 * i}(x1)")
        ops.append(f"    bne    x6, x7, e_fail")

    body = BODY.replace('@N@', str(len(entries))).replace('@OPS@', '\n'.join(ops))
    data = ["", "    .section .data", "    .space 256              # scratch area (words 0..63)",
            "e_table:"]
    for e in entries:
        data.append("    .word " + ", ".join(f"0x{v:08x}" for v in e))

    with open(out, 'w') as f:
        f.write(HEADER + body + "\n".join(data) + "\n")


if __name__ == '__main__':
    main()
